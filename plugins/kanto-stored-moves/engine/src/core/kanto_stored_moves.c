// Called with the four saved move words on the VM stack; caller pops them.
void kanto_move_menu_prepare(SCRIPT_CTX * THIS) OLDCALL BANKED {
    UBYTE *out = ui_text_data;
    const UBYTE header[] = {1,1,3,3,2};
    UBYTE row,at;
    for(at=0;at<sizeof(header);at++) *out++=header[at];
    for(row=0;row<4;row++) {
        INT16 word=THIS->stack_ptr[(INT8)row-4];
        UWORD id=word<0?0:(UWORD)word/100u;
        UBYTE pp=word<0?0:(UWORD)word%100u;
        const char *name=(id>0 && id<=165)?move_names[id-1]:"----";
        *out++=2; *out++=1;
        while(*name) *out++=*name++;
        *out++=' ';
        if(pp>=10) *out++='0'+pp/10;
        *out++='0'+pp%10;
        if(row<3) *out++=10;
    }
    *out=0;
}

