void kanto_party_menu_prepare(SCRIPT_CTX * THIS) OLDCALL BANKED {
    UBYTE *out = ui_text_data;
    const UBYTE header[] = {1,1,3,3,2};
    UBYTE row,at;
    for(at=0;at<sizeof(header);at++) *out++=header[at];
    for(row=0;row<6;row++) {
        INT16 id=THIS->stack_ptr[(INT8)row-6];
        const char *name;
        if(id<=0 || id>151) break;
        if(row) *out++=10;
        *out++=2; *out++=1;
        name=party_names[id-1];
        while(*name) *out++=*name++;
    }
    *out=0;
}
